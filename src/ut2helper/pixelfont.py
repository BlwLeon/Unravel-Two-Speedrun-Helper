GLYPHS: dict[str, list[str]] = {k: v.split("|") for k, v in _RAW.items()}


def glyph(ch: str) -> list[str]:
    return GLYPHS.get(ch.upper(), GLYPHS["?"])


def text_width(text: str, scale: int) -> int:
    if not text:
        return 0
    return (len(text) * (W + 1) - 1) * scale


def text_height(scale: int) -> int:
    return H * scale


def pixels(text: str):
    """Yield (x, y) pixel coordinates (unscaled) of the rendered text."""
    for i, ch in enumerate(text):
        rows = glyph(ch)
        ox = i * (W + 1)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == "#":
                    yield ox + x, y
